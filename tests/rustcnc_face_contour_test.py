def _analytic(**params):
    return C.GeometrySource(kind="analytic", params=params, frame=C.Frame.WORK)


def _rust_suite_task(radius=2.0, *, stock=((-80.0, -80.0, -20.0), (80.0, 80.0, 0.0)),
                     pocket=((-50.0, -30.0, -8.0), (50.0, 30.0, 0.0))):
    base = C.example_pocket_task()
    lo, hi = stock
    plo, phi = pocket
    geometry = _analytic(
        primitive="box_minus_pocket", box_min_mm=lo, box_max_mm=hi,
        pocket_min_mm=plo, pocket_max_mm=phi,
        island_min_mm=[lo[0], lo[1], 1.0], island_max_mm=[lo[0] + 1, lo[1] + 1, 2.0],
        empty_island=True,
    )
    return dataclasses.replace(
        base,
        stock=_analytic(primitive="box", min_mm=lo, max_mm=hi),
        original_part=geometry, operation_target=C.OperationTarget(geometry=geometry),
        grid=C.GridSpec((160, 160, 80), lo, 0.25),
        work_to_machine=C.Transform.translation((0., 0., 0.)),
        tool=dataclasses.replace(base.tool, cutter_kind=C.CutterKind.FLAT,
                                 cutter_radius_mm=radius, shank_radius_mm=radius),
        limits=C.MachineLimits(max_feed_mm_s=30.0, rapid_mm_s=80.0, max_accel_mm_s2=100.0,
                               envelope_min_mm=(-100.0, -100.0, -24.0),
                               envelope_max_mm=(100.0, 100.0, 60.0)),
        initial_state=C.MachineState(position_mm=(0.0, 0.0, 10.0), frame=C.Frame.MACHINE),
    )


def _assert_typed(plan, task):
    plan.validate_for_task(task)
    assert plan.timing_rule is C.TimingRule.EXACT_STOP_CONSTANT_SPEED
    assert plan.frame is C.Frame.MACHINE
    assert all(segment.kind is not C.SegmentKind.ARC for segment in plan.segments)
    assert all(segment.feed_mm_s is not None and segment.feed_mm_s <= task.limits.max_feed_mm_s
               for segment in plan.segments if segment.kind is not C.SegmentKind.RAPID)
    assert all(segment.feed_mm_s is None
               for segment in plan.segments if segment.kind is C.SegmentKind.RAPID)
    for left, right in zip(plan.segments, plan.segments[1:]):
        assert math.dist(left.end_mm, right.start_mm) <= 1e-9
    # Card-specific safety simplification: every rapid is above stock top;
    # contour sub-stock lead ends use a feed lift before any rapid.
    stock_top = task.stock.params["max_mm"][2]
    assert all(segment.start_mm[2] > stock_top and segment.end_mm[2] > stock_top
               for segment in plan.segments if segment.kind is C.SegmentKind.RAPID)


def _one_tag(segments, tag, *, last=False):
    rows = [segment for segment in segments if segment.tag == tag]
    assert len(rows) == 1 or last, (tag, [(row.id, row.tag) for row in segments])
    assert rows
    return rows[-1]


def test_independent_dt316_cw_square_outside_offset_and_complete_coarse_leads():
    """Recorded Rust points are targets; only each quarter arc is two chords."""
    task = _rust_suite_task(6.0)
    segments = rc.emit_contour_loop(
        task, [(-50., 30.), (50., 30.), (50., -30.), (-50., -30.)],
        contour_z=-3., right_compensation=False)
    assert len(segments) <= 72
    assert _one_tag(segments, "entry-rapid").end_mm == pytest.approx((-56., 51., 4.))
    assert _one_tag(segments, "plunge").end_mm == pytest.approx((-56., 51., 3.))
    assert _one_tag(segments, "lead-in-vertical", last=True).end_mm == pytest.approx((-56., 45., -3.))
    assert _one_tag(segments, "lead-in-flat").end_mm == pytest.approx((-56., 42., -3.))
    assert _one_tag(segments, "lead-in-arc", last=True).end_mm == pytest.approx((-50., 36., -3.))
    assert _one_tag(segments, "lead-out-arc", last=True).end_mm == pytest.approx((-44., 42., -3.))
    assert _one_tag(segments, "lead-out-flat").end_mm == pytest.approx((-44., 45., -3.))
    assert _one_tag(segments, "lead-out-vertical", last=True).end_mm == pytest.approx((-44., 51., 3.))
    assert _one_tag(segments, "exit-rapid").end_mm == pytest.approx((-44., 51., 10.))
    cut = [segment for segment in segments if segment.tag == "finish-cutting"]
    assert len(cut) == 12  # 4 lines + 4 arcs × exact two coarse chords.
    assert cut[0].start_mm == pytest.approx((-50., 36., -3.))
    assert cut[0].end_mm == pytest.approx((50., 36., -3.))
    assert cut[2].end_mm == pytest.approx((56., 30., -3.))
    assert cut[3].end_mm == pytest.approx((56., -30., -3.))
    assert cut[4].start_mm == pytest.approx((56., -30., -3.))
    assert cut[5].end_mm == pytest.approx((50., -36., -3.))
    assert cut[6].end_mm == pytest.approx((-50., -36., -3.))
    assert cut[8].end_mm == pytest.approx((-56., -30., -3.))
    assert cut[9].end_mm == pytest.approx((-56., 30., -3.))
    assert cut[-1].end_mm == pytest.approx((-50., 36., -3.))  # closing arc, never dropped.
    mid = cut[1].end_mm
    assert mid[0] == pytest.approx(50. + 6 / math.sqrt(2))
    assert mid[1] == pytest.approx(30. + 6 / math.sqrt(2))


def test_independent_dt316_inside_sharp_offset_and_right_compensation():
    task = _rust_suite_task(6.0)
    ccw = [(-50., 30.), (-50., -30.), (50., -30.), (50., 30.)]
    inner = [segment for segment in rc.emit_contour_loop(task, ccw, contour_z=-3.)
             if segment.tag == "finish-cutting"]
    xs = [point for segment in inner for point in (segment.start_mm[0], segment.end_mm[0])]
    ys = [point for segment in inner for point in (segment.start_mm[1], segment.end_mm[1])]
    assert (min(xs), max(xs), min(ys), max(ys)) == pytest.approx((-44., 44., -24., 24.))
    assert len(inner) == 5  # re-seated split line: all overlap joins, not rolled arcs.
    right = [segment for segment in rc.emit_contour_loop(
        task, [(-50., 30.), (50., 30.), (50., -30.), (-50., -30.)],
        contour_z=-3., right_compensation=True) if segment.tag == "finish-cutting"]
    xs = [point for segment in right for point in (segment.start_mm[0], segment.end_mm[0])]
    assert (min(xs), max(xs)) == pytest.approx((-44., 44.))


