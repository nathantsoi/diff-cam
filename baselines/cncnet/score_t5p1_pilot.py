"""Score an actually captured CNC-Net pilot using the declared physical frame.

This reader never loads third-party pickle files. Native .npy/OBJ outputs are
file-format inputs generated by run_t5p1_pilot.py. Sparse native IOU and bounded
DiffCAM grid metrics are kept distinct, with all resampling choices disclosed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import re

import numpy as np

from benchmarks import contracts as C
from benchmarks import cncnet_adapter as A

REVISION = "ba0652f9941686058c07c98617b9748e72f5f019"
AVERAGE_IOU = re.compile(r"Average IOU:\s*([-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?)")


def digest(path):
    result = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            result.update(chunk)
    return "sha256:" + result.hexdigest()


def metric_values(metrics):
    return {name: C._to_jsonable(value) for name, value in metrics.items()}


def read_native_log_iou(path):
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    matches = AVERAGE_IOU.findall(text)
    if len(matches) != 1:
        raise ValueError(f"expected exactly one native Average IOU, found {len(matches)}")
    value = float(matches[0])
    if not math.isfinite(value) or not 0.0 <= value <= 1.0:
        raise ValueError(f"native Average IOU is outside [0,1]: {value}")
    return value


def array(path):
    values = np.load(path, allow_pickle=False)
    if not np.isfinite(values).all():
        raise ValueError(f"non-finite values in native array {path}")
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prepared", required=True, type=Path)
    parser.add_argument("--work-dir", required=True, type=Path)
    parser.add_argument("--report", required=True, type=Path)
    args = parser.parse_args()
    prepared = args.prepared.resolve(strict=True)
    work = args.work_dir.resolve(strict=True)
    experiment = "t51p1-dev-pocket"
    prepared_summary = json.loads((prepared / "summary.json").read_text())
    summary = json.loads((work / "capture-status.json").read_text())
    if summary["status"] != "native-entrypoint-returned":
        raise ValueError(f"native capture is not complete: {summary}")
    if summary["preparing_task_hash"] != prepared_summary["task_hash"]:
        raise ValueError("prepared task identity differs from native execution")
    if summary["input_off_hash"] != prepared_summary["off_hash"]:
        raise ValueError("input OFF identity differs from native execution")
    native_task_document = json.loads((prepared / "task.json").read_text())
    native_task = C.TaskSpec.from_dict(native_task_document["record"] if isinstance(native_task_document, dict) and "record" in native_task_document else native_task_document)
    if native_task.task_id != "dev-cncnet-box-pocket-island-001":
        raise ValueError("this bounded scorer is scoped to its frozen dev box-pocket")
    frame_data = json.loads((prepared / "frame.json").read_text())
    frame = A.ObjectUnitFrame(tuple(frame_data["centre_work_mm"]), frame_data["mm_per_object_unit"])
    if not math.isclose(frame.mm_per_object_unit, 80.0):
        raise ValueError("frozen comparison expects 80 mm per object unit")
    counts = summary["native_measurements"]
    if counts["optimizer_steps"] != 1 or counts["iou_calls"] != 1 or counts["mesh_calls"] != 1:
        raise ValueError(f"native evaluation budget does not match frozen scope: {counts}")
    dimensions = summary["reconstruction"]["dimensions"]
    expected = [0.25, 0.2, 0.1]
    dimension_tolerance = float(np.finfo(np.float32).eps)
    if not np.allclose(dimensions, expected, rtol=0, atol=dimension_tolerance):
        raise ValueError(f"native extent mismatch: {dimensions} != {expected}")
    current_high = array(work / "native_current_high.npy")
    if current_high.shape != (256, 256, 256):
        raise ValueError(f"expected 256^3 high grid, got {current_high.shape}")
    current_low = array(work / "native_current_low.npy")
    target_low = array(work / "native_target_low.npy")
    log_iou = read_native_log_iou(work / "checkpoints" / experiment / "logfile.log")
    recomputed = A.native_iou_nonnegative_voxels(current_low, target_low)
    if abs(log_iou - recomputed) > 0.500001e-6:
        raise ValueError(f"native log IOU {log_iou} disagrees with recomputation {recomputed}")
    measured_metrics = metric_values(A.score_reconstruction(native_task, frame, current_high, dimensions))

    files = {}
    for path in sorted(work.rglob("*")):
        if path.is_file() and "__pycache__" not in path.parts:
            files[str(path.relative_to(work))] = {
                "sha256": digest(path), "size_bytes": path.stat().st_size,
            }
    mesh_outputs = {}
    for name in ("dev_box_pocket.obj", "dev_box_pocket_smooth.obj"):
        path = work / "output" / experiment / name
        native = A.parse_obj_vertices(path)
        physical = frame.to_work_mm(native)
        text = path.read_text(encoding="utf-8", errors="strict")
        faces = sum(line.startswith("f ") for line in text.splitlines())
        if not faces:
            raise ValueError(f"native mesh has no faces: {path}")
        mesh_outputs[name] = {
            "sha256": digest(path), "vertices": len(native), "triangles": faces,
            "all_vertices_finite": bool(np.isfinite(native).all()),
            "work_mm_bounds": {"min": physical.min(axis=0).tolist(), "max": physical.max(axis=0).tolist()},
            "surface_metric_claim": "none; only finite vertices and the exported physical-frame bounds",
        }
    if summary["reconstruction"].get("positive_is_occupancy") is not True:
        raise ValueError("native field semantic annotation is inconsistent")
    inside_source = bool(np.all((current_high == 0) | (current_high == 1) | (current_high == 0.5)))
    if not inside_source:
        raise ValueError("native geometry field was not the documented sign-derived occupancy")
    result = {
        "schema": "diffcam-cncnet-comparison/1",
        "status": "complete-bounded-native-reconstruction; not a quality or machining comparison",
        "source_revision": REVISION,
        "task_id": native_task.task_id,
        "task_hash": native_task.task_hash,
        "frame": frame.to_dict(),
        "native_scope": {
            "epoch_count": 1, "per_instance_optimizer_steps": counts["optimizer_steps"],
            "dataset_length": 1, "data_workers": 0,
            "pretraining_checkpoint_loaded": False,
            "source_original_epoch_count": summary["source_epoch_count"],
            "compatibility_wrappers": "point-blocked CSG <=1048576 points; Open3D mesh I/O shim; observation only after native evaluation",
            "elapsed_seconds_total_driver": summary["elapsed_seconds"],
            "native_seed": 0,
        },
        "native_metric": {
            "name": "native_negative_voxel_iou_64_cubed",
            "logged_average_iou": log_iou, "independent_recomputed_iou": recomputed,
            "absolute_roundtrip_difference": abs(log_iou - recomputed),
            "unit": "1", "denominator": "union of negative-valued output and negative target sample indices",
            "not_same_as": "DiffCAM retained-material IoU or continuous-mesh Hausdorff distance",
        },
        "diffcam_metrics": measured_metrics,
        "grid_transfer": {
            "representation": "binary retained occupancy from pre-mesh outputs_high",
            "native_sign": "positive > 0.5 is retained reconstruction; exact 0.5 cells reported separately",
            "exact_half_count": int(np.count_nonzero(current_high == 0.5)),
            "grid_shape": list(native_task.grid.shape), "voxel_mm": native_task.grid.voxel_mm,
            "points": "native loader min=-dimension/2, i/N*extent positions, inverse 80mm/object-unit frame",
            "object_dimension_check_atol": dimension_tolerance,
            "interpolation": "nearest represented node; declared first/last-index clamp inside native bbox; outside bbox is excluded; no SDF interpolation or continuous-mesh Hausdorff claim",
        },
        "mesh_outputs": mesh_outputs,
        "artifact_files": files,
        "executable_disposition": A.executable_disposition(),
        "capture_status_sha256": digest(work / "capture-status.json"),
    }
    output = args.report.expanduser().resolve(strict=False)
    if output.exists():
        raise ValueError(f"refusing to overwrite comparison report: {output}")
    A.write_json(output, result)
    print(json.dumps({
        "status": result["status"], "native_iou": log_iou,
        "diffcam_iou": measured_metrics["iou"]["value"],
        "residual_mm3": measured_metrics["residual_volume_mm3"]["value"],
        "gouge_mm3": measured_metrics["gouge_volume_mm3"]["value"],
        "report": str(output),
    }, sort_keys=True))


if __name__ == "__main__":
    main()
