"""Clean-room CNC controller dialect specifications for LinuxCNC RS274 and Haas NGC.

Implements two physical G-code dialect specifications inheriting from
:class:`cam.dialects.base.ControllerDialectSpec`:

* :class:`LinuxCNCRS274DialectSpec` (``rs274``) -- LinuxCNC / NIST RS274NGC
  with explicit ``G91.1`` incremental arc-centre offsets and ``G64 P<tol>``
  path-blending tolerance or ``G61`` exact-stop control.
* :class:`HaasNGCDialectSpec` (``haas``) -- Haas Next Generation Control (NGC)
  with 5-digit ``O00001``..``O99999`` program numbers, ``%`` framing, mandatory
  decimal points on all coordinate/feed/smoothing words, and ``G187 P2 E<tol>``
  smoothing (never ``G64``, which triggers Haas Alarm 302).
"""

from __future__ import annotations

import dataclasses
import math
import re
from typing import Sequence

import numpy as np

from benchmarks.contracts import Frame, MotionPlan, TaskSpec, TimingRule
from cam.config import MachineConfig
from cam.dialects.base import (
    ControllerDialect,
    ControllerDialectSpec,
    HardwareSyntaxError,
    axis_words,
    build_motion_lines,
    check_real_word_decimals,
    feed_out,
    fmt_int,
    fmt_real,
    format_program_number,
    len_out,
    sanitize_comment,
    strip_nc_comments,
    tool_table_comment,
    xy_words,
)

_WORD_TOKEN_RE = re.compile(r"([A-Za-z])\s*([-+]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+))")
_HAAS_O_HEADER_RE = re.compile(r"^O([0-9]{5})(?![0-9.])")
_MAKINO_SMOOTHING_MCODES = frozenset({250, 251, 252, 253})


def _validate_units(units: str) -> None:
    if units not in ("mm", "inch"):
        raise ValueError(f"unsupported NC units {units!r}; expected 'mm' or 'inch'")


def _validate_positions(positions: np.ndarray) -> np.ndarray:
    arr = np.asarray(positions, dtype=np.float64)
    if arr.ndim != 2 or arr.shape[1] != 3:
        raise ValueError(f"positions must be (T, 3); got {arr.shape}")
    if len(arr) == 0:
        raise ValueError("positions is empty")
    if not np.isfinite(arr).all():
        raise ValueError("positions must contain only finite values")
    return arr


def _validate_shop_plan(plan: MotionPlan, blend_tolerance_mm: float) -> tuple[float, float, float]:
    from cam.posts import UnsupportedPostError

    if plan.frame != Frame.MACHINE:
        raise UnsupportedPostError("shop posting requires a machine-frame MotionPlan")
    if not plan.initial_state.known or plan.initial_state.position_mm is None:
        raise UnsupportedPostError("cannot emit shop program from an unknown initial state")
    if not math.isfinite(blend_tolerance_mm) or blend_tolerance_mm <= 0.0:
        raise ValueError(
            f"blend_tolerance_mm must be finite and positive; got {blend_tolerance_mm!r}"
        )
    return plan.initial_state.position_mm


class LinuxCNCRS274DialectSpec(ControllerDialectSpec):
    """Clean-room LinuxCNC / NIST RS274NGC dialect specification."""

    dialect = ControllerDialect.RS274
    display_name = "LinuxCNC / NIST RS274NGC"
    file_extension = ".ngc"
    force_decimal = False
    program_digits = None
    max_program_number = 99999
    leading_percent = False
    trailing_percent = False
    shop_xyz_decimals_mm = 3
    shop_xyz_decimals_inch = 4
    shop_feed_decimals_mm = 2
    shop_feed_decimals_inch = 3

    def format_typed_program(
        self,
        motion_lines: Sequence[str],
        *,
        plan: MotionPlan,
        task: TaskSpec,
        config: MachineConfig,
    ) -> str:
        del task
        blended = plan.timing_rule == TimingRule.BLENDED_ACCEL_BOUNDED
        tol_prec = 4 if config.units == "inch" else 3
        tol_out = fmt_real(float(len_out(0.05, config)), tol_prec, force_decimal=False)
        path_ctrl = f"G54 G64 P{tol_out}" if blended else "G54 G61"
        offset_line = (
            f"G43 H{fmt_int(config.h_register, name='H')}"
            if plan.initial_state.length_offset_applied
            else "G49"
        )
        lines = [
            "(Generated by diff-cam typed MotionPlan RS274 post)",
            config.units_code,
            "G17 G40 G49 G80 G90 G94 G91.1",
            path_ctrl,
            offset_line,
            *motion_lines,
            "M2",
        ]
        return "\n".join(lines) + "\n"

    def format_shop_program(
        self,
        plan: MotionPlan,
        task: TaskSpec,
        config: MachineConfig,
        *,
        case_label: str | None = None,
        blend_tolerance_mm: float = 0.05,
    ) -> str:
        init_pos_mm = _validate_shop_plan(plan, blend_tolerance_mm)
        label = sanitize_comment(case_label or config.program_name)
        xyz_p = self.shop_xyz_decimals(config.units)
        feed_p = self.shop_feed_decimals(config.units)
        init_work = task.work_to_machine.inverse().apply(init_pos_mm)
        init_out = len_out(np.asarray(init_work, dtype=np.float64), config)
        tol_out = fmt_real(
            float(len_out(blend_tolerance_mm, config)),
            xyz_p,
            force_decimal=True,
        )
        offset_line = (
            f"G43 H{fmt_int(config.h_register, name='H')}"
            if plan.initial_state.length_offset_applied
            else "G49"
        )
        path_ctrl = (
            f"G64 P{tol_out}"
            if plan.timing_rule == TimingRule.BLENDED_ACCEL_BOUNDED
            else "G61"
        )
        motion_lines = build_motion_lines(
            plan,
            task,
            config,
            xyz_precision=xyz_p,
            feed_precision=feed_p,
            force_decimal=True,
        )

        lines = [
            "%",
            f"(DIFFCAM MIT LINUXCNC RS274 - {label})",
            tool_table_comment(task, config),
            "G90 G94 G17 G91.1 G40 G49 G80",
            config.units_code,
            f"T{fmt_int(config.tool_number, name='T')} M06",
            f"S{fmt_int(config.spindle_rpm, name='S')} M03",
            config.work_offset,
            offset_line,
            "G90 G53 G0 Z0.0",
            f"G0 {xy_words(float(init_out[0]), float(init_out[1]), xyz_p, force_decimal=True)}",
            f"G0 Z{fmt_real(float(init_out[2]), xyz_p, force_decimal=True)}",
        ]
        if config.coolant:
            lines.append("M08")
        lines.append(path_ctrl)
        lines.extend(motion_lines)
        if config.coolant:
            lines.append("M09")
        lines.extend(
            [
                "M05",
                "G90 G53 G0 Z0.0",
                "M30",
                "%",
            ]
        )
        return "\n".join(lines) + "\n"

    def format_legacy_positions_program(
        self,
        positions: np.ndarray,
        config: MachineConfig = MachineConfig(),
    ) -> str:
        arr = _validate_positions(positions)
        pts_out = len_out(config.to_wcs(arr), config)
        feed_val = feed_out(config.feed, config)
        p = config.precision

        lines = [
            "(Generated by diff-cam cam.posts.RS274Post)",
            config.units_code,
            "G90",
            "G61",
            f"G0 {axis_words(pts_out[0], p, force_decimal=False)}",
        ]
        if len(pts_out) > 1:
            lines.append(f"F{fmt_real(feed_val, p, force_decimal=False)}")
            for pt in pts_out[1:]:
                lines.append(f"G1 {axis_words(pt, p, force_decimal=False)}")
        lines.append("M2")
        return "\n".join(lines) + "\n"

    def verify_hardware_syntax(
        self,
        nc_text: str,
        *,
        units: str = "mm",
        shop_mode: bool = False,
    ) -> None:
        _validate_units(units)
        for line_no, raw in enumerate(nc_text.splitlines(), start=1):
            code = strip_nc_comments(raw)
            if not code or code == "%":
                continue
            for ltr_raw, num_str in _WORD_TOKEN_RE.findall(code):
                ltr = ltr_raw.upper()
                val = float(num_str)
                if ltr == "G":
                    if abs(val - 187.0) <= 1e-9:
                        raise HardwareSyntaxError(
                            f"Line {line_no}: Haas-proprietary G{num_str} is invalid on LinuxCNC RS274"
                        )
                    if abs(val - 5.1) <= 1e-9:
                        raise HardwareSyntaxError(
                            f"Line {line_no}: FANUC-proprietary G{num_str} is invalid on LinuxCNC RS274"
                        )
                elif ltr == "M":
                    if int(val) == val and int(val) in _MAKINO_SMOOTHING_MCODES:
                        raise HardwareSyntaxError(
                            f"Line {line_no}: Makino-proprietary M{num_str} is invalid on LinuxCNC RS274"
                        )

        if shop_mode:
            check_real_word_decimals(
                nc_text,
                max_xyz_decimals=self.shop_xyz_decimals(units),
                max_feed_decimals=self.shop_feed_decimals(units),
            )


class HaasNGCDialectSpec(ControllerDialectSpec):
    """Clean-room Haas Next Generation Control (NGC) dialect specification."""

    dialect = ControllerDialect.HAAS
    display_name = "Haas Next Generation Control (NGC)"
    file_extension = ".nc"
    force_decimal = True
    program_digits = 5
    max_program_number = 99999
    leading_percent = True
    trailing_percent = True
    shop_xyz_decimals_mm = 3
    shop_xyz_decimals_inch = 4
    shop_feed_decimals_mm = 2
    shop_feed_decimals_inch = 3

    def format_typed_program(
        self,
        motion_lines: Sequence[str],
        *,
        plan: MotionPlan,
        task: TaskSpec,
        config: MachineConfig,
    ) -> str:
        del task
        prog_num = format_program_number(config.program_number, digits=5, max_number=99999)
        prog_label = sanitize_comment(config.program_name)
        blended = plan.timing_rule == TimingRule.BLENDED_ACCEL_BOUNDED
        tol_prec = 4 if config.units == "inch" else 3
        tol_str = fmt_real(float(len_out(0.05, config)), tol_prec, force_decimal=True)
        path_ctrl_lines = (
            [config.work_offset, f"G187 P2 E{tol_str}"]
            if blended
            else [f"{config.work_offset} G61"]
        )
        offset_line = (
            f"G43 H{fmt_int(config.h_register, name='H')}"
            if plan.initial_state.length_offset_applied
            else "G49"
        )

        lines = [
            "%",
            f"{prog_num} ({prog_label})",
            "(Generated by diff-cam typed MotionPlan Haas NGC post)",
            "G90 G94 G17 G40 G49 G80",
            config.units_code,
            *path_ctrl_lines,
            f"T{fmt_int(config.tool_number, name='T')} M06",
            offset_line,
            f"S{fmt_int(config.spindle_rpm, name='S')} M03",
        ]
        if config.coolant:
            lines.append("M08")
        lines.extend(motion_lines)
        if blended:
            lines.append("G187")
        if config.coolant:
            lines.append("M09")
        lines.extend(
            [
                "M05",
                "M30",
                "%",
            ]
        )
        return "\n".join(lines) + "\n"

    def format_shop_program(
        self,
        plan: MotionPlan,
        task: TaskSpec,
        config: MachineConfig,
        *,
        case_label: str | None = None,
        blend_tolerance_mm: float = 0.05,
    ) -> str:
        init_pos_mm = _validate_shop_plan(plan, blend_tolerance_mm)
        prog_num = format_program_number(config.program_number, digits=5, max_number=99999)
        label = sanitize_comment(case_label or config.program_name)
        xyz_p = self.shop_xyz_decimals(config.units)
        feed_p = self.shop_feed_decimals(config.units)
        init_work = task.work_to_machine.inverse().apply(init_pos_mm)
        init_out = len_out(np.asarray(init_work, dtype=np.float64), config)
        blended = plan.timing_rule == TimingRule.BLENDED_ACCEL_BOUNDED
        tol_str = fmt_real(
            float(len_out(blend_tolerance_mm, config)),
            xyz_p,
            force_decimal=True,
        )
        offset_line = (
            f"G43 H{fmt_int(config.h_register, name='H')}"
            if plan.initial_state.length_offset_applied
            else "G49"
        )
        path_ctrl = f"G187 P2 E{tol_str}" if blended else "G61"
        motion_lines = build_motion_lines(
            plan,
            task,
            config,
            xyz_precision=xyz_p,
            feed_precision=feed_p,
            force_decimal=True,
        )

        lines = [
            "%",
            f"{prog_num} (DIFFCAM MIT HAAS MINI MILL NGC - {label})",
            tool_table_comment(task, config),
            "G90 G94 G17 G40 G49 G80",
            config.units_code,
            f"T{fmt_int(config.tool_number, name='T')} M06",
            f"S{fmt_int(config.spindle_rpm, name='S')} M03",
            config.work_offset,
            offset_line,
            "G90 G53 G0 Z0.0",
            f"G0 {xy_words(float(init_out[0]), float(init_out[1]), xyz_p, force_decimal=True)}",
            f"G0 Z{fmt_real(float(init_out[2]), xyz_p, force_decimal=True)}",
        ]
        if config.coolant:
            lines.append("M08")
        lines.append(path_ctrl)
        lines.extend(motion_lines)
        if blended:
            lines.append("G187")
        if config.coolant:
            lines.append("M09")
        lines.extend(
            [
                "M05",
                "G90 G53 G0 Z0.0",
                "M30",
                "%",
            ]
        )
        return "\n".join(lines) + "\n"

    def format_legacy_positions_program(
        self,
        positions: np.ndarray,
        config: MachineConfig = MachineConfig(),
    ) -> str:
        arr = _validate_positions(positions)
        pts_out = len_out(config.to_wcs(arr), config)
        feed_val = feed_out(config.feed, config)
        plunge_val = feed_out(config.plunge_feed, config)
        p = config.precision
        safe = fmt_real(float(len_out(config.safe_z_mm, config)), p, force_decimal=True)
        prog_num = format_program_number(config.program_number, digits=5, max_number=99999)
        prog_label = sanitize_comment(config.program_name)
        rpm_val = float(config.spindle_rpm)
        if not math.isfinite(rpm_val):
            raise ValueError(f"spindle_rpm must be finite; got {config.spindle_rpm!r}")
        spindle_rpm = fmt_int(round(rpm_val), name="S")

        lines = [
            "%",
            f"{prog_num} ({prog_label})",
            "(Post: Haas Mini Mill -- generated by diff-cam cam.posts.HaasPost)",
            "G17 G40 G49 G80 G90",
            config.units_code,
            config.work_offset,
        ]
        if config.stock_origin_in is not None:
            ox, oy, oz = len_out(config.stock_origin_vec, config)
            p_reg = int(config.work_offset[1:]) - 53
            lines.append(
                f"G10 L2 P{fmt_int(p_reg, name='P')} "
                f"{axis_words((ox, oy, oz), p, force_decimal=True)}"
            )
        lines.extend(
            [
                f"T{fmt_int(config.tool_number, name='T')} M06",
                f"G43 H{fmt_int(config.h_register, name='H')} Z{safe}",
                f"S{spindle_rpm} M03",
            ]
        )
        if config.coolant:
            lines.append("M08")

        x0, y0, z0 = pts_out[0]
        lines.append(f"G00 {xy_words(float(x0), float(y0), p, force_decimal=True)}")
        lines.append(
            f"G01 Z{fmt_real(float(z0), p, force_decimal=True)} "
            f"F{fmt_real(plunge_val, p, force_decimal=True)}"
        )
        if len(pts_out) > 1:
            lines.append(f"F{fmt_real(feed_val, p, force_decimal=True)}")
            for pt in pts_out[1:]:
                lines.append(f"G01 {axis_words(pt, p, force_decimal=True)}")

        lines.append(f"G00 Z{safe}")
        if config.coolant:
            lines.append("M09")
        lines.extend(
            [
                "M05",
                "G90 G53 G00 Z0.0",
                "M30",
                "%",
            ]
        )
        return "\n".join(lines) + "\n"

    def verify_hardware_syntax(
        self,
        nc_text: str,
        *,
        units: str = "mm",
        shop_mode: bool = False,
    ) -> None:
        _validate_units(units)
        non_empty = [line.strip() for line in nc_text.splitlines() if line.strip()]
        if len(non_empty) < 2 or non_empty[0] != "%" or non_empty[-1] != "%":
            raise HardwareSyntaxError(
                "Haas NGC programs must begin and end with standalone '%' framing lines"
            )
        if any(strip_nc_comments(line) == "%" for line in non_empty[1:-1]):
            raise HardwareSyntaxError(
                "Haas NGC programs must not contain mid-program '%' framing characters"
            )

        saw_o_header = False
        for line_no, raw in enumerate(nc_text.splitlines(), start=1):
            code = strip_nc_comments(raw)
            if not code or code == "%":
                continue
            if not saw_o_header:
                match = _HAAS_O_HEADER_RE.match(code)
                if match is None or int(match.group(1)) < 1:
                    raise HardwareSyntaxError(
                        f"Line {line_no}: Haas NGC first executable line must start with an exact "
                        f"5-digit O00001..O99999 program number; got {code!r}"
                    )
                saw_o_header = True

            tokens = _WORD_TOKEN_RE.findall(code)
            is_g187_block = False
            for ltr_raw, num_str in tokens:
                ltr = ltr_raw.upper()
                val = float(num_str)
                if ltr == "G":
                    if 64.0 <= val < 65.0 or abs(val - 64.0) <= 1e-9:
                        raise HardwareSyntaxError(
                            f"Line {line_no}: G{num_str} is invalid on Haas NGC (Alarm 302: INVALID G CODE); "
                            "use G187 smoothing or G61 exact stop"
                        )
                    if abs(val - 91.1) <= 1e-9:
                        raise HardwareSyntaxError(
                            f"Line {line_no}: G{num_str} is LinuxCNC-specific and invalid on Haas NGC"
                        )
                    if abs(val - 5.1) <= 1e-9:
                        raise HardwareSyntaxError(
                            f"Line {line_no}: FANUC AICC G{num_str} is invalid on Haas NGC; use G187"
                        )
                    if abs(val - 187.0) <= 1e-9:
                        is_g187_block = True
                elif ltr == "M":
                    if int(val) == val and int(val) in _MAKINO_SMOOTHING_MCODES:
                        raise HardwareSyntaxError(
                            f"Line {line_no}: Makino M{num_str} is invalid on Haas NGC"
                        )

            if is_g187_block:
                for ltr_raw, num_str in tokens:
                    if ltr_raw.upper() == "P":
                        p_val = float(num_str)
                        if "." in num_str or int(p_val) != p_val or int(p_val) not in (1, 2, 3):
                            raise HardwareSyntaxError(
                                f"Line {line_no}: Haas NGC G187 P smoothness level must be integer 1, 2, or 3; "
                                f"got P{num_str}"
                            )

        if not saw_o_header:
            raise HardwareSyntaxError(
                "Haas NGC program has no executable blocks and is missing a 5-digit O00001..O99999 header"
            )

        check_real_word_decimals(
            nc_text,
            max_xyz_decimals=self.shop_xyz_decimals(units) if shop_mode else None,
            max_feed_decimals=self.shop_feed_decimals(units) if shop_mode else None,
        )


LINUXCNC_RS274_SPEC = LinuxCNCRS274DialectSpec()
HAAS_NGC_SPEC = HaasNGCDialectSpec()


def format_haas_ngc_shop_program(
    plan: MotionPlan,
    task: TaskSpec,
    config: MachineConfig | None = None,
    *,
    program_number: int | None = None,
    case_label: str | None = None,
    blend_tolerance_mm: float = 0.05,
) -> str:
    """Emit and syntax-verify a standalone Haas NGC shop-floor G-code program."""
    if config is None:
        cfg = MachineConfig(
            units="mm",
            tool_number=task.tool.tool_number,
            length_offset=task.tool.tool_number,
            program_number=1 if program_number is None else program_number,
        )
    elif program_number is not None:
        cfg = dataclasses.replace(config, program_number=program_number)
    else:
        cfg = config

    nc_text = HAAS_NGC_SPEC.format_shop_program(
        plan,
        task,
        cfg,
        case_label=case_label,
        blend_tolerance_mm=blend_tolerance_mm,
    )
    HAAS_NGC_SPEC.verify_hardware_syntax(nc_text, units=cfg.units, shop_mode=True)
    return nc_text


