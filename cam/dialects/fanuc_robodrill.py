"""Clean-room FANUC 0i/30i/31i and FANUC Robodrill Alpha (31i-B5) dialect specs.

Hardware characteristics modeled here:
- 4-digit EIA program numbers ``O0001``..``O8999`` (``O9000``..``O9999`` reserved
  for Fanuc system/OEM macros) framed by leading and trailing ``%`` lines.
- Mandatory decimal points on all floating-point coordinate, arc-offset, radius,
  and feedrate words (``X``, ``Y``, ``Z``, ``I``, ``J``, ``K``, ``R``, ``F``) so
  values are never interpreted in least-input increments (``0.001 mm`` / ``0.0001 in``).
- FANUC AICC II look-ahead smoothing via standalone ``G05.1 Q1 R5`` (where ``R5``
  is an integer precision level ``1..10`` with NO decimal point) paired with
  standalone ``G05.1 Q0`` prior to coolant/spindle shutdown and Z home retract.
- Machine Z home retract distinction:
  * Generic ``FANUC 0i/30i/31i``: ``G28 G91 Z0.0`` followed by ``G90``.
  * ``FANUC Robodrill Alpha (31i-B5)``: ``G90 G53 G0 Z0.0`` (machine-coordinate
    Z home; ``G28`` is rejected on Robodrill).
"""

from __future__ import annotations

import re
from typing import Sequence

import numpy as np

from benchmarks.contracts import MotionPlan, TaskSpec, TimingRule
from cam.config import MachineConfig
from cam.dialects.base import (
    ControllerDialect,
    ControllerDialectSpec,
    HardwareSyntaxError,
    axis_words,
    build_motion_lines,
    check_real_word_decimals,
    feed_out,
    fmt_int,
    fmt_real,
    format_program_number,
    len_out,
    sanitize_comment,
    strip_nc_comments,
    tool_table_comment,
    xy_words,
)

_TOKEN_RE = re.compile(r"([A-Za-z])\s*([-+]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+))")
_O_WORD_RE = re.compile(r"(?<![A-Za-z])[Oo]\s*[-+]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)")
_STRICT_O4_RE = re.compile(r"O([0-9]{4})")


class FanucDialectSpec(ControllerDialectSpec):
    """Clean-room specification for FANUC 0i / 30i / 31i & Compact series."""

    dialect = ControllerDialect.FANUC
    display_name = "FANUC 0i / 30i / 31i Series"
    file_extension = ".nc"
    force_decimal = True
    program_digits = 4
    max_program_number = 8999
    leading_percent = True
    trailing_percent = True
    shop_xyz_decimals_mm = 3
    shop_xyz_decimals_inch = 4
    shop_feed_decimals_mm = 0
    shop_feed_decimals_inch = 1

    _typed_post_comment = "(Generated by diff-cam typed MotionPlan FANUC post)"
    _shop_banner_prefix = "DIFFCAM MIT FANUC"
    _legacy_post_comment = "(Post: FANUC 0i/30i/31i -- generated by diff-cam)"
    _home_z_retract_lines: tuple[str, ...] = ("G28 G91 Z0.0", "G90")
    _forbid_g28: bool = False

    def _format_prog_num(self, program_number: int) -> str:
        assert self.program_digits is not None
        return format_program_number(
            program_number,
            digits=self.program_digits,
            max_number=self.max_program_number,
        )

    @staticmethod
    def _validate_positions(positions: np.ndarray) -> np.ndarray:
        arr = np.asarray(positions, dtype=np.float64)
        if arr.ndim != 2 or arr.shape[1] != 3:
            raise ValueError(f"positions must be (T, 3); got {arr.shape}")
        if len(arr) == 0:
            raise ValueError("positions is empty")
        if not np.isfinite(arr).all():
            raise ValueError("positions must contain only finite values")
        return arr

    def format_typed_program(
        self,
        motion_lines: Sequence[str],
        *,
        plan: MotionPlan,
        task: TaskSpec,
        config: MachineConfig,
    ) -> str:
        prog_num = self._format_prog_num(config.program_number)
        prog_label = sanitize_comment(config.program_name)
        unit_code = config.units_code
        blended = plan.timing_rule == TimingRule.BLENDED_ACCEL_BOUNDED
        offset_line = (
            f"G43 H{fmt_int(config.h_register, name='H')}"
            if plan.initial_state.length_offset_applied
            else "G49"
        )

        lines: list[str] = [
            "%",
            f"{prog_num} ({prog_label})",
            self._typed_post_comment,
            "G90 G94 G17 G49 G40 G80",
            unit_code,
            config.work_offset if blended else f"{config.work_offset} G61",
            f"T{fmt_int(config.tool_number, name='T')} M06",
            offset_line,
            f"S{fmt_int(config.spindle_rpm, name='S')} M03",
        ]
        if config.coolant:
            lines.append("M08")
        if blended:
            lines.append("G05.1 Q1 R5")
        lines.extend(motion_lines)
        if blended:
            lines.append("G05.1 Q0")
        if config.coolant:
            lines.append("M09")
        lines.extend(("M05", "M30", "%"))
        return "\n".join(lines) + "\n"

    def format_shop_program(
        self,
        plan: MotionPlan,
        task: TaskSpec,
        config: MachineConfig,
        *,
        case_label: str | None = None,
        blend_tolerance_mm: float = 0.05,
    ) -> str:
        del blend_tolerance_mm  # FANUC AICC II uses discrete R1..R10 level (R5)
        if not plan.initial_state.known or plan.initial_state.position_mm is None:
            raise ValueError("shop program requires a known initial_state.position_mm")

        prog_num = self._format_prog_num(config.program_number)
        unit_code = config.units_code
        label = sanitize_comment(case_label or config.program_name)
        xyz_p = self.shop_xyz_decimals(config.units)
        feed_p = self.shop_feed_decimals(config.units)
        init_work = task.work_to_machine.inverse().apply(plan.initial_state.position_mm)
        init_out = len_out(np.asarray(init_work, dtype=np.float64), config)
        blended = plan.timing_rule == TimingRule.BLENDED_ACCEL_BOUNDED
        offset_line = (
            f"G43 H{fmt_int(config.h_register, name='H')}"
            if plan.initial_state.length_offset_applied
            else "G49"
        )

        lines: list[str] = [
            "%",
            f"{prog_num} ({self._shop_banner_prefix} - {label})",
            tool_table_comment(task, config),
            "G90 G94 G17 G49 G40 G80",
            unit_code,
            f"T{fmt_int(config.tool_number, name='T')} M06",
            f"S{fmt_int(config.spindle_rpm, name='S')} M03",
            config.work_offset,
            offset_line,
            *self._home_z_retract_lines,
            f"G0 {xy_words(float(init_out[0]), float(init_out[1]), xyz_p, force_decimal=True)}",
            f"G0 Z{fmt_real(float(init_out[2]), xyz_p, force_decimal=True)}",
        ]
        if config.coolant:
            lines.append("M08")
        lines.append("G05.1 Q1 R5" if blended else "G61")
        lines.extend(
            build_motion_lines(
                plan,
                task,
                config,
                xyz_precision=xyz_p,
                feed_precision=feed_p,
                force_decimal=True,
            )
        )
        if blended:
            lines.append("G05.1 Q0")
        if config.coolant:
            lines.append("M09")
        lines.append("M05")
        lines.extend(self._home_z_retract_lines)
        lines.extend(("M30", "%"))
        return "\n".join(lines) + "\n"

    def format_legacy_positions_program(
        self,
        positions: np.ndarray,
        config: MachineConfig,
    ) -> str:
        pts_norm = self._validate_positions(positions)
        prog_num = self._format_prog_num(config.program_number)
        prog_label = sanitize_comment(config.program_name)
        unit_code = config.units_code
        pts_out = len_out(config.to_wcs(pts_norm), config)
        feed_val = feed_out(config.feed, config)
        plunge_val = feed_out(config.plunge_feed, config)
        p = config.precision
        safe = fmt_real(float(len_out(config.safe_z_mm, config)), p, force_decimal=True)

        lines: list[str] = [
            "%",
            f"{prog_num} ({prog_label})",
            self._legacy_post_comment,
            "G90 G94 G17 G49 G40 G80",
            unit_code,
            *self._home_z_retract_lines,
            f"T{fmt_int(config.tool_number, name='T')} M06",
            f"S{fmt_int(config.spindle_rpm, name='S')} M03",
            config.work_offset,
        ]

        if config.stock_origin_in is not None:
            if not re.fullmatch(r"G5[4-9]", config.work_offset):
                raise ValueError(
                    f"G10 L2 work-offset programming requires G54..G59; got {config.work_offset!r}"
                )
            ox, oy, oz = len_out(config.stock_origin_vec, config)
            p_reg = int(config.work_offset[1:]) - 53
            lines.append(
                f"G10 L2 P{fmt_int(p_reg, name='P')} "
                f"X{fmt_real(float(ox), p, force_decimal=True)} "
                f"Y{fmt_real(float(oy), p, force_decimal=True)} "
                f"Z{fmt_real(float(oz), p, force_decimal=True)}"
            )

        x0, y0, z0 = pts_out[0]
        lines.append(f"G00 {xy_words(float(x0), float(y0), p, force_decimal=True)}")
        lines.append(f"G43 H{fmt_int(config.h_register, name='H')} Z{safe}")
        if config.coolant:
            lines.append("M08")
        lines.append(
            f"G01 Z{fmt_real(float(z0), p, force_decimal=True)} "
            f"F{fmt_real(float(plunge_val), p, force_decimal=True)}"
        )
        if len(pts_out) > 1:
            lines.append(f"F{fmt_real(float(feed_val), p, force_decimal=True)}")
            for pt in pts_out[1:]:
                lines.append(f"G01 {axis_words(pt, p, force_decimal=True)}")

        lines.append(f"G00 Z{safe}")
        if config.coolant:
            lines.append("M09")
        lines.append("M05")
        lines.extend(self._home_z_retract_lines)
        lines.extend(("M30", "%"))
        return "\n".join(lines) + "\n"

    def verify_hardware_syntax(
        self,
        nc_text: str,
        *,
        units: str = "mm",
        shop_mode: bool = False,
    ) -> None:
        if units not in ("mm", "inch"):
            raise ValueError(f"unsupported NC units {units!r}; expected 'mm' or 'inch'")

        non_empty = [ln.strip() for ln in nc_text.splitlines() if ln.strip()]
        if len(non_empty) < 2:
            raise HardwareSyntaxError("NC program is empty or missing '%' tape delimiters")
        if non_empty[0] != "%":
            raise HardwareSyntaxError(
                f"FANUC program must start with leading '%', got {non_empty[0]!r}"
            )
        if non_empty[-1] != "%":
            raise HardwareSyntaxError(
                f"FANUC program must end with trailing '%', got {non_empty[-1]!r}"
            )

        max_xyz = self.shop_xyz_decimals(units) if shop_mode else None
        max_feed = self.shop_feed_decimals(units) if shop_mode else None
        check_real_word_decimals(
            nc_text,
            g05_r_is_integer=True,
            max_xyz_decimals=max_xyz,
            max_feed_decimals=max_feed,
        )

        o_count = 0
        aicc_active = False
        ever_enabled_aicc = False
        saw_m30 = False

        for line_no, raw in enumerate(nc_text.splitlines(), start=1):
            code = strip_nc_comments(raw)
            if not code or code == "%":
                continue

            for o_match in _O_WORD_RE.finditer(code):
                o_raw = o_match.group(0)
                strict = _STRICT_O4_RE.fullmatch(o_raw)
                if strict is None:
                    raise HardwareSyntaxError(
                        f"Line {line_no}: FANUC requires exact 4-digit program number "
                        f"O0001..O{self.max_program_number:04d}, got {o_raw!r}"
                    )
                prog_no = int(strict.group(1))
                if not (1 <= prog_no <= self.max_program_number):
                    raise HardwareSyntaxError(
                        f"Line {line_no}: FANUC program number {o_raw} is outside "
                        f"O0001..O{self.max_program_number:04d} (O9000..O9999 reserved for macros)"
                    )
                o_count += 1

            tokens = _TOKEN_RE.findall(code)
            g_vals: list[float] = []
            m_vals: list[int] = []
            words_by_letter: dict[str, list[str]] = {}
            for ltr_raw, num_str in tokens:
                ltr = ltr_raw.upper()
                words_by_letter.setdefault(ltr, []).append(num_str)
                if ltr == "G":
                    g_vals.append(float(num_str))
                elif ltr == "M":
                    m_vals.append(int(float(num_str)))

            if "E" in words_by_letter:
                raise HardwareSyntaxError(
                    f"Line {line_no}: Haas 'E' smoothing word is invalid on {self.display_name}"
                )

            for g_val in g_vals:
                if abs(g_val - 64.0) <= 1e-9 or int(g_val) == 64:
                    raise HardwareSyntaxError(
                        f"Line {line_no}: G64 path blending is invalid on {self.display_name}; "
                        "use AICC II G05.1 Q1 R5 or G61"
                    )
                if abs(g_val - 187.0) <= 1e-9:
                    raise HardwareSyntaxError(
                        f"Line {line_no}: Haas G187 smoothing is invalid on {self.display_name}"
                    )
                if abs(g_val - 91.1) <= 1e-9:
                    raise HardwareSyntaxError(
                        f"Line {line_no}: RS274 G91.1 arc mode is invalid on {self.display_name}"
                    )
                if self._forbid_g28 and abs(g_val - 28.0) <= 1e-9:
                    raise HardwareSyntaxError(
                        f"Line {line_no}: G28 reference return is forbidden on {self.display_name}; "
                        "use G90 G53 G0 Z0.0"
                    )

            for m_val in m_vals:
                if m_val in (250, 251, 252, 253):
                    raise HardwareSyntaxError(
                        f"Line {line_no}: Makino M{m_val} smoothing code is invalid on {self.display_name}"
                    )

            is_g05 = any(abs(g_val - 5.1) <= 1e-9 for g_val in g_vals)
            if is_g05:
                if saw_m30:
                    raise HardwareSyntaxError(
                        f"Line {line_no}: G05.1 cannot appear after M30"
                    )
                if any(ax in words_by_letter for ax in ("X", "Y", "Z", "I", "J", "K", "F")):
                    raise HardwareSyntaxError(
                        f"Line {line_no}: G05.1 must appear on a standalone block without motion words"
                    )
                q_list = words_by_letter.get("Q", [])
                if len(q_list) != 1:
                    raise HardwareSyntaxError(
                        f"Line {line_no}: G05.1 requires exactly one Q0 or Q1 mode word"
                    )
                q_val = int(q_list[0])
                if q_val == 1:
                    r_list = words_by_letter.get("R", [])
                    if r_list:
                        if len(r_list) != 1:
                            raise HardwareSyntaxError(
                                f"Line {line_no}: duplicate R word on G05.1 block"
                            )
                        r_val = int(r_list[0])
                        if not (1 <= r_val <= 10):
                            raise HardwareSyntaxError(
                                f"Line {line_no}: G05.1 Q1 R precision level must be in 1..10, got R{r_val}"
                            )
                    aicc_active = True
                    ever_enabled_aicc = True
                elif q_val == 0:
                    if "R" in words_by_letter:
                        raise HardwareSyntaxError(
                            f"Line {line_no}: G05.1 Q0 cancel block must not include an R word"
                        )
                    if not aicc_active:
                        raise HardwareSyntaxError(
                            f"Line {line_no}: G05.1 Q0 appears without an active G05.1 Q1"
                        )
                    aicc_active = False
                else:
                    raise HardwareSyntaxError(
                        f"Line {line_no}: G05.1 Q word must be Q1 (enable) or Q0 (cancel), got Q{q_val}"
                    )

            if 30 in m_vals or 2 in m_vals:
                if aicc_active:
                    raise HardwareSyntaxError(
                        f"Line {line_no}: G05.1 Q1 is still active at program end; "
                        "missing matching G05.1 Q0 before M30"
                    )
                if 30 in m_vals:
                    saw_m30 = True

        if o_count == 0:
            raise HardwareSyntaxError(
                f"Missing 4-digit FANUC program number (O0001..O{self.max_program_number:04d})"
            )
        if o_count > 1:
            raise HardwareSyntaxError(
                f"Expected a single O program number header, found {o_count}"
            )
        if aicc_active:
            raise HardwareSyntaxError(
                "G05.1 Q1 was never canceled; missing G05.1 Q0 before M30"
            )
        if ever_enabled_aicc and not saw_m30:
            raise HardwareSyntaxError(
                "G05.1 Q1/Q0 program must terminate with M30"
            )


class RobodrillDialectSpec(FanucDialectSpec):
    """Clean-room specification for FANUC Robodrill Alpha D21SiA5/MiA5/LiA5 (31i-B5)."""

    dialect = ControllerDialect.ROBODRILL
    display_name = "FANUC Robodrill Alpha (31i-B5)"

    _typed_post_comment = "(Generated by diff-cam typed MotionPlan FANUC Robodrill post)"
    _shop_banner_prefix = "DIFFCAM MIT FANUC ROBODRILL"
    _legacy_post_comment = "(Post: FANUC Robodrill Alpha 31i-B5 -- generated by diff-cam)"
    _home_z_retract_lines: tuple[str, ...] = ("G90 G53 G0 Z0.0",)
    _forbid_g28: bool = True


FANUC_SPEC = FanucDialectSpec()
ROBODRILL_SPEC = RobodrillDialectSpec()

